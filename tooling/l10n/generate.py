#!/usr/bin/env python3
"""Generates qml/ProcessLama/L10n.qml from the ARB catalogs in l10n/.

The English catalog is the template; every other catalog must have the same
keys and placeholders. QML reads strings with `L10n.t("key")` and
`L10n.t("key", [arg, ...])`; arguments fill the placeholders in the order the
template declares them.

  python3 tooling/l10n/generate.py          write the singleton
  python3 tooling/l10n/generate.py --check  fail when it is stale
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOGS = ROOT / "l10n"
OUTPUT = ROOT / "qml" / "ProcessLama" / "L10n.qml"
TEMPLATE = "en"
PLACEHOLDER = re.compile(r"\{([A-Za-z_][A-Za-z0-9_]*)\}")


def load(locale: str) -> dict:
    return json.loads((CATALOGS / f"app_{locale}.arb").read_text(encoding="utf-8"))


def messages(catalog: dict) -> dict[str, str]:
    return {key: value for key, value in catalog.items() if not key.startswith("@")}


def placeholders(template: dict, key: str) -> list[str]:
    declared = template.get(f"@{key}", {}).get("placeholders", {})
    names = list(declared.keys())
    for name in PLACEHOLDER.findall(template[key]):
        if name not in names:
            names.append(name)
    return names


def render() -> str:
    template = load(TEMPLATE)
    locales = sorted(path.stem.removeprefix("app_") for path in CATALOGS.glob("app_*.arb"))
    keys = sorted(messages(template))
    params = {key: placeholders(template, key) for key in keys}
    tables: dict[str, dict[str, str]] = {}
    for locale in locales:
        catalog = messages(load(locale))
        missing = sorted(set(keys) - set(catalog))
        extra = sorted(set(catalog) - set(keys))
        if missing or extra:
            raise SystemExit(f"{locale}: missing {missing[:5]} extra {extra[:5]}")
        for key in keys:
            used = set(PLACEHOLDER.findall(catalog[key]))
            if not used <= set(params[key]):
                raise SystemExit(f"{locale}.{key}: unknown placeholders {used - set(params[key])}")
        tables[locale] = {key: catalog[key] for key in keys}

    lines = [
        "// GENERATED by tooling/l10n/generate.py from l10n/*.arb. Do not edit.",
        "pragma Singleton",
        "import QtQuick",
        "",
        "QtObject {",
        "    /// The active language; unknown codes fall back to English.",
        '    property string language: "en"',
        f"    readonly property var languages: {json.dumps(locales)}",
        "    readonly property var strings: language === \"de\" ? _de : _en",
        "",
        "    /// The message `key` with `args` filling its placeholders in order.",
        "    function t(key, args) {",
        "        let text = strings[key]",
        "        if (text === undefined)",
        "            return key",
        "        const names = _params[key]",
        "        if (names && args) {",
        "            for (let i = 0; i < names.length && i < args.length; ++i)",
        "                text = text.split(\"{\" + names[i] + \"}\").join(String(args[i]))",
        "        }",
        "        return text",
        "    }",
        "",
        f"    readonly property var _params: ({json.dumps({k: v for k, v in params.items() if v}, ensure_ascii=False, sort_keys=True)})",
    ]
    for locale in locales:
        lines.append(f"    readonly property var _{locale}: ({json.dumps(tables[locale], ensure_ascii=False, sort_keys=True)})")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run tooling/l10n/generate.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
