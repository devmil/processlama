#!/usr/bin/env python3
"""Generates the remote helper contract for Rust and Dart from contract.json.

Outputs
  rust-core/wire/src/contract.rs                      constants and enums for the helper
                                                       and the core
  lib/models/remote_contract.g.dart                   model enums: failure codes, targets,
                                                       install results
  lib/repositories/impl/remote/wire/contract.g.dart   limits, names and name-based mappers
                                                       between wire values and model enums

The helper build ID is the compatibility version from rust-core/remote-helper/COMPATIBILITY
as 40 decimal digits; Rust reads it in processlama_wire's build script, Dart gets it here.

  generate.py           write the outputs
  generate.py --check   fail when an output is missing or out of date
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONTRACT = ROOT / "tooling" / "remote_wire" / "contract.json"
COMPATIBILITY = ROOT / "rust-core" / "remote-helper" / "COMPATIBILITY"
RUST_OUT = ROOT / "rust-core" / "wire" / "src" / "contract.rs"
DART_MODELS_OUT = ROOT / "lib" / "models" / "remote_contract.g.dart"
DART_WIRE_OUT = ROOT / "lib" / "repositories" / "impl" / "remote" / "wire" / "contract.g.dart"

HEADER = "@generated by tooling/remote_wire/generate.py from tooling/remote_wire/contract.json. Do not edit."

# Contract value lists that map onto existing app enums, by Dart type and import.
DART_MODEL_MAPPINGS = {
    "signalOutcomes": ("SignalOutcome", "../../../../models/models.dart"),
    "networkSources": ("NetworkRateSource", "../../../../models/models.dart"),
    "networkReasons": ("NetworkUnavailableReason", "../../../../models/models.dart"),
    "processStatuses": ("ProcessStatus", "../../../../models/models.dart"),
    "signals": ("ProcessSignal", "../../../process_repository.dart"),
}


def pascal(name: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", name)
    result = ""
    for part in parts:
        if not part:
            continue
        result += part[0].upper() + part[1:]
    return result


def camel(name: str) -> str:
    value = pascal(name)
    return value[0].lower() + value[1:]


def snake_upper(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def compatibility_version() -> int:
    for line in COMPATIBILITY.read_text(encoding="utf-8").splitlines():
        key, _, value = line.strip().partition(" ")
        if key == "version":
            return int(value)
    raise SystemExit("rust-core/remote-helper/COMPATIBILITY has no version")


def build_id(version: int) -> str:
    return str(version).rjust(40, "0")


def names(entries) -> list[str]:
    return [entry if isinstance(entry, str) else entry["name"] for entry in entries]


def rust_enum(type_name: str, values: list[str], doc: str) -> str:
    variants = "\n".join(f"    {pascal(value)}," for value in values)
    arms_str = "\n".join(f'            Self::{pascal(v)} => "{v}",' for v in values)
    arms_parse = "\n".join(f'            "{v}" => Some(Self::{pascal(v)}),' for v in values)
    all_values = ", ".join(f"Self::{pascal(v)}" for v in values)
    return f"""/// {doc}
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum {type_name} {{
{variants}
}}

impl {type_name} {{
    pub const ALL: [Self; {len(values)}] = [{all_values}];

    pub const fn as_str(self) -> &'static str {{
        match self {{
{arms_str}
        }}
    }}

    pub fn parse(value: &str) -> Option<Self> {{
        match value {{
{arms_parse}
            _ => None,
        }}
    }}
}}
"""


def generate_rust(contract: dict) -> str:
    out = [f"// {HEADER}", "#![allow(clippy::all)]", ""]
    out.append(f'pub const MAGIC: &str = "{contract["magic"]}";')
    out.append(f"pub const PROTOCOL_MAJOR: u64 = {contract['protocol']['major']};")
    out.append(f"pub const PROTOCOL_MINOR: u64 = {contract['protocol']['minor']};")
    for key in ("helperExecutable", "installRoot", "cacheRoot", "bootstrapPrefix", "installPrefix"):
        out.append(f'pub const {snake_upper(key)}: &str = "{contract[key]}";')
    out.append("")
    for name, limit in contract["limits"].items():
        out.append(f"/// {limit['doc']}")
        out.append(f"pub const {snake_upper(name)}: usize = {limit['value']};")
    out.append("")
    for name, value in contract["deadlinesMs"].items():
        out.append(f"pub const {snake_upper(name)}_DEADLINE_MS: u64 = {value};")
    out.append("")

    targets = contract["targets"]
    out.append(rust_enum("Target", names(targets), "A helper build target."))
    for field in ("os", "arch", "uname", "rust"):
        arms = "\n".join(
            f'            Self::{pascal(t["name"])} => "{t[field]}",' for t in targets
        )
        method = "rust_triple" if field == "rust" else field
        out.append(
            f"""impl Target {{
    pub const fn {method}(self) -> &'static str {{
        match self {{
{arms}
        }}
    }}
}}
"""
        )

    failures = contract["failureCodes"]
    out.append(rust_enum("FailureCode", names(failures), "A typed connection failure."))
    arms = "\n".join(
        f"            Self::{pascal(f['name'])} => {'true' if f['retryable'] else 'false'},"
        for f in failures
    )
    out.append(
        f"""impl FailureCode {{
    /// Whether the reconnect schedule retries this failure.
    pub const fn retryable(self) -> bool {{
        match self {{
{arms}
        }}
    }}
}}
"""
    )
    out.append(rust_enum("CallErrorCode", contract["callErrors"], "A typed call error."))
    methods = contract["methods"]
    out.append(rust_enum("Method", names(methods), "A call method."))
    arms = "\n".join(
        f"            Self::{pascal(m['name'])} => {'true' if m['queue'] == 'bulk' else 'false'},"
        for m in methods
    )
    out.append(
        f"""impl Method {{
    /// Whether the call runs on the bulk queue.
    pub const fn is_bulk(self) -> bool {{
        match self {{
{arms}
        }}
    }}
}}
"""
    )
    out.append(rust_enum("Topic", names(contract["topics"]), "A subscription topic."))
    out.append(rust_enum("Signal", contract["signals"], "A process signal."))
    out.append(rust_enum("SignalOutcome", contract["signalOutcomes"], "The outcome of a signal."))
    out.append(rust_enum("InstallResult", contract["installResults"], "The install script's result."))
    out.append(rust_enum("NetworkSource", contract["networkSources"], "Where network rates come from."))
    out.append(rust_enum("NetworkReason", contract["networkReasons"], "Why network rates are missing."))
    out.append(
        rust_enum("SectionState", contract["detailSectionStates"], "An inspector section's state.")
    )
    out.append(rust_enum("ProcessStatus", contract["processStatuses"], "A process status."))
    return "\n".join(out).rstrip() + "\n"


def dart_doc(text: str) -> str:
    return f"  /// {text}\n"


def generate_dart_models(contract: dict) -> str:
    lines = [f"// {HEADER}", ""]
    failures = contract["failureCodes"]
    lines.append("/// A typed remote connection failure. Flutter localizes each code; SSH")
    lines.append("/// output is never parsed.")
    lines.append("enum RemoteFailureCode {")
    for entry in failures:
        lines.append(dart_doc(entry["doc"]).rstrip("\n"))
        lines.append(f"  {entry['name']}(retryable: {'true' if entry['retryable'] else 'false'}),")
    lines[-1] = lines[-1][:-1] + ";"
    lines.append("")
    lines.append("  const RemoteFailureCode({required this.retryable});")
    lines.append("")
    lines.append("  /// Whether the reconnect schedule retries this failure.")
    lines.append("  final bool retryable;")
    lines.append("}")
    lines.append("")
    lines.append("/// A remote helper build target.")
    lines.append("enum RemoteHelperTarget {")
    targets = contract["targets"]
    for target in targets:
        lines.append(
            f"  {camel(target['name'])}('{target['name']}', '{target['os']}', "
            f"'{target['arch']}', '{target['uname']}'),"
        )
    lines[-1] = lines[-1][:-1] + ";"
    lines.append("")
    lines.append("  const RemoteHelperTarget(this.wireName, this.os, this.arch, this.uname);")
    lines.append("")
    lines.append("  /// The descriptor and directory name, for example `linux-x86_64`.")
    lines.append("  final String wireName;")
    lines.append("  final String os;")
    lines.append("  final String arch;")
    lines.append("")
    lines.append("  /// `uname -s`/`uname -m` as the launch script reports it.")
    lines.append("  final String uname;")
    lines.append("")
    lines.append("  static RemoteHelperTarget? fromWire(String value) {")
    lines.append("    for (final target in values) {")
    lines.append("      if (target.wireName == value || target.uname == value) return target;")
    lines.append("    }")
    lines.append("    return null;")
    lines.append("  }")
    lines.append("}")
    lines.append("")
    lines.append("/// The install script's result line.")
    lines.append("enum RemoteInstallResult {")
    lines.append("  " + ", ".join(contract["installResults"]) + ",")
    lines.append("}")
    return "\n".join(lines) + "\n"


def dart_string_set(name: str, values: list[str]) -> list[str]:
    body = ", ".join(f"'{value}'" for value in values)
    return [f"const {name} = <String>{{{body}}};", ""]


def generate_dart_wire(contract: dict, version: int) -> str:
    lines = [f"// {HEADER}", ""]
    imports = sorted({path for _, path in DART_MODEL_MAPPINGS.values()} | {"../../../../models/models.dart"})
    for path in imports:
        lines.append(f"import '{path}';")
    lines.append("")
    lines.append(f"/// The helper compatibility version (rust-core/remote-helper/COMPATIBILITY).")
    lines.append(f"const remoteHelperCompatibility = {version};")
    lines.append("")
    lines.append("/// The only helper build this client talks to.")
    lines.append(f"const remoteHelperBuildId = '{build_id(version)}';")
    lines.append("")
    lines.append(f"const remoteHelperMagic = '{contract['magic']}';")
    lines.append(f"const remoteProtocolMajor = {contract['protocol']['major']};")
    lines.append(f"const remoteProtocolMinor = {contract['protocol']['minor']};")
    for key in ("helperExecutable", "installRoot", "cacheRoot", "bootstrapPrefix", "installPrefix"):
        lines.append(f"const remote{pascal(key)} = '{contract[key]}';")
    lines.append("")
    lines.append("abstract final class RemoteWireLimits {")
    for name, limit in contract["limits"].items():
        lines.append(dart_doc(limit["doc"]).rstrip("\n"))
        lines.append(f"  static const {name} = {limit['value']};")
    lines.append("}")
    lines.append("")
    lines.append("abstract final class RemoteWireDeadlines {")
    for name, value in contract["deadlinesMs"].items():
        lines.append(f"  static const {name} = Duration(milliseconds: {value});")
    lines.append("}")
    lines.append("")
    lines.append("abstract final class RemoteWireMethods {")
    for method in contract["methods"]:
        lines.append(dart_doc(method["doc"]).rstrip("\n"))
        lines.append(f"  static const {camel(method['name'])} = '{method['name']}';")
    lines.append("}")
    lines.append("")
    lines += dart_string_set(
        "remoteBulkMethods",
        [m["name"] for m in contract["methods"] if m["queue"] == "bulk"],
    )
    lines.append("abstract final class RemoteWireTopics {")
    for topic in contract["topics"]:
        lines.append(f"  static const {camel(topic['name'])} = '{topic['name']}';")
    lines.append("}")
    lines.append("")
    lines += dart_string_set("remoteCallErrorCodes", contract["callErrors"])
    lines += dart_string_set("remoteSectionStates", contract["detailSectionStates"])

    lines.append("RemoteFailureCode? remoteFailureCodeFromWire(String value) =>")
    lines.append("    switch (value) {")
    for entry in contract["failureCodes"]:
        lines.append(f"      '{entry['name']}' => RemoteFailureCode.{entry['name']},")
    lines.append("      _ => null,")
    lines.append("    };")
    lines.append("")
    lines.append("RemoteInstallResult? remoteInstallResultFromWire(String value) =>")
    lines.append("    switch (value) {")
    for value in contract["installResults"]:
        lines.append(f"      '{value}' => RemoteInstallResult.{value},")
    lines.append("      _ => null,")
    lines.append("    };")
    lines.append("")
    for key, (dart_type, _) in DART_MODEL_MAPPINGS.items():
        values = contract[key]
        function = dart_type[0].lower() + dart_type[1:]
        lines.append(f"{dart_type}? {function}FromWire(String value) => switch (value) {{")
        for value in values:
            lines.append(f"  '{value}' => {dart_type}.{value},")
        lines.append("  _ => null,")
        lines.append("};")
        lines.append("")
        lines.append(f"String {function}ToWire({dart_type} value) => switch (value) {{")
        for value in values:
            lines.append(f"  {dart_type}.{value} => '{value}',")
        lines.append("};")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def dart_format(path: Path, text: str) -> str:
    """Formats generated Dart with the repository's formatter, in place of the real file."""
    result = subprocess.run(
        ["dart", "format", "--output=show", f"--stdin-name={path.relative_to(ROOT)}"],
        input=text,
        capture_output=True,
        text=True,
        cwd=ROOT,
        check=True,
    )
    return result.stdout


def outputs() -> dict[Path, str]:
    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))
    version = compatibility_version()
    return {
        RUST_OUT: generate_rust(contract),
        DART_MODELS_OUT: dart_format(DART_MODELS_OUT, generate_dart_models(contract)),
        DART_WIRE_OUT: dart_format(DART_WIRE_OUT, generate_dart_wire(contract, version)),
    }


def rustfmt(text: str) -> str:
    result = subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input=text,
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout


def main(arguments: list[str]) -> int:
    check = arguments == ["--check"]
    if arguments and not check:
        print(__doc__, file=sys.stderr)
        return 2
    stale = []
    for path, text in outputs().items():
        if path.suffix == ".rs":
            text = rustfmt(text)
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        print("generated remote contract is out of date: " + ", ".join(stale), file=sys.stderr)
        print("run python3 tooling/remote_wire/generate.py", file=sys.stderr)
        return 1
    print("remote contract " + ("is current" if check else "generated"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
